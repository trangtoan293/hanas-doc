
{#
    Intermediate Model: int_fact_pl
    Prepare P&L data from Raw Vault for Fact Detail.
    This is where Business Logic (PL classification by SBV_GL_SL) resides.
    
    NOTE: Logic ported from Legacy SQL to handle complex AC_NO mappings and Sign flips.
    ADDED: DV_LDT for incremental filtering support.
#}

WITH sat_gl_base AS (
    SELECT
        DV_HKEY_HUB_GL,
        CAST(EOD_DATE AS DATE) AS COB_DATE,
        POS_CD AS BRANCH_CODE,
        DR_CR_FLG,
        FCY_AMT * NUM_DUPLICATES AS FCY_AMT,
        LCY_AMT * NUM_DUPLICATES AS LCY_AMT,
        DV_LDT
    FROM {{ ref('sat_gl') }}
),

hub_gl AS (
    SELECT 
        DV_HKEY_HUB_GL,
        AC_NO
    FROM {{ ref('hub_gl') }}
),

sat_snp_gl_sbv AS (
    SELECT
        DV_HKEY_HUB_GL,
        POS_CD,
        SBV_GL_SL
    FROM {{ ref('sat_snp_gl_sbv') }}
),

-- Join and filter valid branches
branch_gl_sbv AS (
    SELECT
        g.COB_DATE,
        g.BRANCH_CODE,
        g.DV_LDT,
        SUM(CASE WHEN g.DR_CR_FLG='C' THEN g.FCY_AMT ELSE -g.FCY_AMT END) AS FCY_AMT,
        SUM(CASE WHEN g.DR_CR_FLG='C' THEN g.LCY_AMT ELSE -g.LCY_AMT END) AS LCY_AMT,
        h.AC_NO,
        sbv.SBV_GL_SL
    FROM sat_gl_base g
    JOIN hub_gl h ON g.DV_HKEY_HUB_GL = h.DV_HKEY_HUB_GL
    JOIN sat_snp_gl_sbv sbv ON g.DV_HKEY_HUB_GL = sbv.DV_HKEY_HUB_GL AND g.BRANCH_CODE = sbv.POS_CD
    GROUP BY g.COB_DATE, g.BRANCH_CODE, g.DV_LDT, h.AC_NO, sbv.SBV_GL_SL
),

-- =============================================================================
-- PL Classification Logic (Ported from Legacy SQL)
-- =============================================================================
pl_classified AS (
    -- 7.1 Thu nhập từ lãi (Interest Income)
    SELECT COB_DATE, BRANCH_CODE, '7.1' AS PL_CODE,
           CASE WHEN SUM(FCY_AMT) > 0 THEN SUM(FCY_AMT) ELSE 0 END AS FCY_OUTSTND,
           CASE WHEN SUM(LCY_AMT) > 0 THEN SUM(LCY_AMT) ELSE 0 END AS LCY_OUTSTND,
           MAX(DV_LDT) AS DV_LDT
    FROM branch_gl_sbv
    WHERE SUBSTR(SBV_GL_SL,1,2) IN ('70') AND SUBSTR(SBV_GL_SL,1,4) NOT IN ('7060')
    GROUP BY COB_DATE, BRANCH_CODE

    UNION ALL

    SELECT COB_DATE, BRANCH_CODE, '7.1' AS PL_CODE,
           CASE WHEN SUM(FCY_AMT) > 0 THEN SUM(FCY_AMT) ELSE 0 END AS FCY_OUTSTND,
           CASE WHEN SUM(LCY_AMT) > 0 THEN SUM(LCY_AMT) ELSE 0 END AS LCY_OUTSTND,
           MAX(DV_LDT) AS DV_LDT
    FROM branch_gl_sbv
    WHERE AC_NO IN ('9446027046','9409117045','9409407043')
    GROUP BY COB_DATE, BRANCH_CODE

    UNION ALL

    -- 7.1 from 80 (Sign Flip)
    SELECT COB_DATE, BRANCH_CODE, '7.1' AS PL_CODE,
           CASE WHEN SUM(FCY_AMT) < 0 THEN -SUM(FCY_AMT) ELSE 0 END AS FCY_OUTSTND,
           CASE WHEN SUM(LCY_AMT) < 0 THEN -SUM(LCY_AMT) ELSE 0 END AS LCY_OUTSTND,
           MAX(DV_LDT) AS DV_LDT
    FROM branch_gl_sbv
    WHERE SUBSTR(SBV_GL_SL,1,2) IN ('80')
    GROUP BY COB_DATE, BRANCH_CODE

    UNION ALL

    -- 7.2 Chi phí lãi (Interest Expense)
    SELECT COB_DATE, BRANCH_CODE, '7.2' AS PL_CODE,
           CASE WHEN SUM(FCY_AMT) > 0 THEN SUM(FCY_AMT) ELSE 0 END AS FCY_OUTSTND,
           CASE WHEN SUM(LCY_AMT) > 0 THEN SUM(LCY_AMT) ELSE 0 END AS LCY_OUTSTND,
           MAX(DV_LDT) AS DV_LDT
    FROM branch_gl_sbv
    WHERE SUBSTR(SBV_GL_SL,1,2) IN ('71')
    GROUP BY COB_DATE, BRANCH_CODE

    UNION ALL

    -- 7.2 from Specific AC (Sign Flip)
    SELECT COB_DATE, BRANCH_CODE, '7.2' AS PL_CODE,
           CASE WHEN SUM(FCY_AMT) < 0 THEN -SUM(FCY_AMT) ELSE 0 END AS FCY_OUTSTND,
           CASE WHEN SUM(LCY_AMT) < 0 THEN -SUM(LCY_AMT) ELSE 0 END AS LCY_OUTSTND,
           MAX(DV_LDT) AS DV_LDT
    FROM branch_gl_sbv
    WHERE AC_NO IN ('9446027046','9409117045','9409407043','9400297045','9421007049','9421337049')
    GROUP BY COB_DATE, BRANCH_CODE

    UNION ALL

    -- 7.2 from 81 (Sign Flip)
    SELECT COB_DATE, BRANCH_CODE, '7.2' AS PL_CODE,
           CASE WHEN SUM(FCY_AMT) < 0 THEN -SUM(FCY_AMT) ELSE 0 END AS FCY_OUTSTND,
           CASE WHEN SUM(LCY_AMT) < 0 THEN -SUM(LCY_AMT) ELSE 0 END AS LCY_OUTSTND,
           MAX(DV_LDT) AS DV_LDT
    FROM branch_gl_sbv
    WHERE SUBSTR(SBV_GL_SL,1,2) IN ('81')
    GROUP BY COB_DATE, BRANCH_CODE

    UNION ALL

    SELECT COB_DATE, BRANCH_CODE, '7.2' AS PL_CODE,
           CASE WHEN SUM(FCY_AMT) < 0 THEN -SUM(FCY_AMT) ELSE 0 END AS FCY_OUTSTND,
           CASE WHEN SUM(LCY_AMT) < 0 THEN -SUM(LCY_AMT) ELSE 0 END AS LCY_OUTSTND,
           MAX(DV_LDT) AS DV_LDT
    FROM branch_gl_sbv
    WHERE AC_NO IN ('9346137049')
    GROUP BY COB_DATE, BRANCH_CODE

    UNION ALL

    SELECT COB_DATE, BRANCH_CODE, '7.2' AS PL_CODE,
           CASE WHEN SUM(FCY_AMT) < 0 THEN -SUM(FCY_AMT) ELSE 0 END AS FCY_OUTSTND,
           CASE WHEN SUM(LCY_AMT) < 0 THEN -SUM(LCY_AMT) ELSE 0 END AS LCY_OUTSTND,
           MAX(DV_LDT) AS DV_LDT
    FROM branch_gl_sbv
    WHERE AC_NO IN ('9334227042','9334237045')
    GROUP BY COB_DATE, BRANCH_CODE

    UNION ALL

    -- 7.3 Thu nhập dịch vụ (Service Income)
    SELECT COB_DATE, BRANCH_CODE, '7.3' AS PL_CODE,
           CASE WHEN SUM(FCY_AMT) > 0 THEN SUM(FCY_AMT) ELSE 0 END AS FCY_OUTSTND,
           CASE WHEN SUM(LCY_AMT) > 0 THEN SUM(LCY_AMT) ELSE 0 END AS LCY_OUTSTND,
           MAX(DV_LDT) AS DV_LDT
    FROM branch_gl_sbv
    WHERE SUBSTR(SBV_GL_SL,1,2) IN ('72')
    GROUP BY COB_DATE, BRANCH_CODE

    UNION ALL

    -- 7.3 from 82 (Sign Flip)
    SELECT COB_DATE, BRANCH_CODE, '7.3' AS PL_CODE,
           CASE WHEN SUM(FCY_AMT) < 0 THEN -SUM(FCY_AMT) ELSE 0 END AS FCY_OUTSTND,
           CASE WHEN SUM(LCY_AMT) < 0 THEN -SUM(LCY_AMT) ELSE 0 END AS LCY_OUTSTND,
           MAX(DV_LDT) AS DV_LDT
    FROM branch_gl_sbv
    WHERE SUBSTR(SBV_GL_SL,1,2) IN ('82')
    GROUP BY COB_DATE, BRANCH_CODE

    UNION ALL

    -- 7.4 Chi phí hoạt động (Operating Expense)
    SELECT COB_DATE, BRANCH_CODE, '7.4' AS PL_CODE,
           CASE WHEN SUM(FCY_AMT) > 0 THEN SUM(FCY_AMT) ELSE 0 END AS FCY_OUTSTND,
           CASE WHEN SUM(LCY_AMT) > 0 THEN SUM(LCY_AMT) ELSE 0 END AS LCY_OUTSTND,
           MAX(DV_LDT) AS DV_LDT
    FROM branch_gl_sbv
    WHERE SUBSTR(SBV_GL_SL,1,2) IN ('74')
    GROUP BY COB_DATE, BRANCH_CODE

    UNION ALL

    -- 7.4 from 84 (Sign Flip)
    SELECT COB_DATE, BRANCH_CODE, '7.4' AS PL_CODE,
           CASE WHEN SUM(FCY_AMT) < 0 THEN -SUM(FCY_AMT) ELSE 0 END AS FCY_OUTSTND,
           CASE WHEN SUM(LCY_AMT) < 0 THEN -SUM(LCY_AMT) ELSE 0 END AS LCY_OUTSTND,
           MAX(DV_LDT) AS DV_LDT
    FROM branch_gl_sbv
    WHERE SUBSTR(SBV_GL_SL,1,2) IN ('84') AND SUBSTR(SBV_GL_SL,1,3) NOT IN ('849')
    GROUP BY COB_DATE, BRANCH_CODE

    UNION ALL

    SELECT COB_DATE, BRANCH_CODE, '7.4' AS PL_CODE,
           CASE WHEN SUM(FCY_AMT) < 0 THEN -SUM(FCY_AMT) ELSE 0 END AS FCY_OUTSTND,
           CASE WHEN SUM(LCY_AMT) < 0 THEN -SUM(LCY_AMT) ELSE 0 END AS LCY_OUTSTND,
           MAX(DV_LDT) AS DV_LDT
    FROM branch_gl_sbv
    WHERE AC_NO IN ('9418987046','9420287048','9420297041')
    GROUP BY COB_DATE, BRANCH_CODE

    UNION ALL

    -- 7.5 Thu nhập khác (Other Income)
    SELECT COB_DATE, BRANCH_CODE, '7.5' AS PL_CODE,
           CASE WHEN SUM(FCY_AMT) > 0 THEN SUM(FCY_AMT) ELSE 0 END AS FCY_OUTSTND,
           CASE WHEN SUM(LCY_AMT) > 0 THEN SUM(LCY_AMT) ELSE 0 END AS LCY_OUTSTND,
           MAX(DV_LDT) AS DV_LDT
    FROM branch_gl_sbv
    WHERE AC_NO IN ('9418987046','9421347042','9422207042','9422607040','9422917044','9422918409','9422927047','9422947043','9422957046','9422987045','9422997048','9423807043')
    GROUP BY COB_DATE, BRANCH_CODE

    UNION ALL

    -- 7.5 from 89, 849 (Sign Flip)
    SELECT COB_DATE, BRANCH_CODE, '7.5' AS PL_CODE,
           CASE WHEN SUM(FCY_AMT) < 0 THEN -SUM(FCY_AMT) ELSE 0 END AS FCY_OUTSTND,
           CASE WHEN SUM(LCY_AMT) < 0 THEN -SUM(LCY_AMT) ELSE 0 END AS LCY_OUTSTND,
           MAX(DV_LDT) AS DV_LDT
    FROM branch_gl_sbv
    WHERE SUBSTR(SBV_GL_SL,1,2) IN ('89') OR SUBSTR(SBV_GL_SL,1,3) IN ('849')
    GROUP BY COB_DATE, BRANCH_CODE

    UNION ALL

    -- 7.6 (SBV 78)
    SELECT COB_DATE, BRANCH_CODE, '7.6' AS PL_CODE,
           CASE WHEN SUM(FCY_AMT) > 0 THEN SUM(FCY_AMT) ELSE 0 END AS FCY_OUTSTND,
           CASE WHEN SUM(LCY_AMT) > 0 THEN SUM(LCY_AMT) ELSE 0 END AS LCY_OUTSTND,
           MAX(DV_LDT) AS DV_LDT
    FROM branch_gl_sbv
    WHERE SUBSTR(SBV_GL_SL,1,2) IN ('78')
    GROUP BY COB_DATE, BRANCH_CODE

    UNION ALL

    -- 8.1 Chi phí quản lý (Management Expense)
    SELECT COB_DATE, BRANCH_CODE, '8.1' AS PL_CODE,
           CASE WHEN SUM(FCY_AMT) > 0 THEN SUM(FCY_AMT) ELSE 0 END AS FCY_OUTSTND,
           CASE WHEN SUM(LCY_AMT) > 0 THEN SUM(LCY_AMT) ELSE 0 END AS LCY_OUTSTND,
           MAX(DV_LDT) AS DV_LDT
    FROM branch_gl_sbv
    WHERE SUBSTR(SBV_GL_SL,1,2) IN ('85')
    GROUP BY COB_DATE, BRANCH_CODE

    UNION ALL

    -- 8.2 Chi phí dự phòng (Provision Expense)
    SELECT COB_DATE, BRANCH_CODE, '8.2' AS PL_CODE,
           CASE WHEN SUM(FCY_AMT) > 0 THEN SUM(FCY_AMT) ELSE 0 END AS FCY_OUTSTND,
           CASE WHEN SUM(LCY_AMT) > 0 THEN SUM(LCY_AMT) ELSE 0 END AS LCY_OUTSTND,
           MAX(DV_LDT) AS DV_LDT
    FROM branch_gl_sbv
    WHERE AC_NO IN ('9300307048','9330147045','9330167041','9330087040','9326007047','9326017040','9330027042','9333167048','9330017049','9330107043','9330077047','9345337044','9345327041','9330137042','9330277041','9330287044','9330297047','9300957045','9300917043','9300927046','9300937049','9300947042','9330317040','9330937048','9330267048','9333707042','9326027043','9330007046')
    GROUP BY COB_DATE, BRANCH_CODE

    UNION ALL

    -- 8.3 Chi phí khác (Other Expense)
    SELECT COB_DATE, BRANCH_CODE, '8.3' AS PL_CODE,
           CASE WHEN SUM(FCY_AMT) > 0 THEN SUM(FCY_AMT) ELSE 0 END AS FCY_OUTSTND,
           CASE WHEN SUM(LCY_AMT) > 0 THEN SUM(LCY_AMT) ELSE 0 END AS LCY_OUTSTND,
           MAX(DV_LDT) AS DV_LDT
    FROM branch_gl_sbv
    WHERE (SUBSTR(SBV_GL_SL,1,2) IN ('83','86','87') OR SUBSTR(SBV_GL_SL,1,4) IN ('8826')) AND SUBSTR(SBV_GL_SL,1,4) NOT IN ('8330')
    GROUP BY COB_DATE, BRANCH_CODE

    UNION ALL

    -- 8.4 Chi phí thuế (Tax Expense)
    SELECT COB_DATE, BRANCH_CODE, '8.4' AS PL_CODE,
           CASE WHEN SUM(FCY_AMT) > 0 THEN SUM(FCY_AMT) ELSE 0 END AS FCY_OUTSTND,
           CASE WHEN SUM(LCY_AMT) > 0 THEN SUM(LCY_AMT) ELSE 0 END AS LCY_OUTSTND,
           MAX(DV_LDT) AS DV_LDT
    FROM branch_gl_sbv
    WHERE SUBSTR(SBV_GL_SL,1,4) IN ('8830')
    GROUP BY COB_DATE, BRANCH_CODE

    UNION ALL

    -- 9.1 Lợi nhuận (Profit)
    SELECT COB_DATE, BRANCH_CODE, '9.1' AS PL_CODE,
           CASE WHEN SUM(FCY_AMT) > 0 THEN SUM(FCY_AMT) ELSE 0 END AS FCY_OUTSTND,
           CASE WHEN SUM(LCY_AMT) > 0 THEN SUM(LCY_AMT) ELSE 0 END AS LCY_OUTSTND,
           MAX(DV_LDT) AS DV_LDT
    FROM branch_gl_sbv
    WHERE SUBSTR(SBV_GL_SL,1,3) IN ('882')
    GROUP BY COB_DATE, BRANCH_CODE

    UNION ALL

    -- 9.1 from Specific AC (Sign Flip)
    SELECT COB_DATE, BRANCH_CODE, '9.1' AS PL_CODE,
           CASE WHEN SUM(FCY_AMT) < 0 THEN -SUM(FCY_AMT) ELSE 0 END AS FCY_OUTSTND,
           CASE WHEN SUM(LCY_AMT) < 0 THEN -SUM(LCY_AMT) ELSE 0 END AS LCY_OUTSTND,
           MAX(DV_LDT) AS DV_LDT
    FROM branch_gl_sbv
    WHERE AC_NO IN ('9422074181','9422127041','9422167043','9422177046','9422217045','9422227048','9422247044','9422307049','9422314184','9422317042','9422484182','9422507043','9423027043','9423907040','9423917043')
    GROUP BY COB_DATE, BRANCH_CODE
)

SELECT 
    COB_DATE,
    BRANCH_CODE,
    PL_CODE,
    SUM(FCY_OUTSTND) AS FCY_OUTSTND,
    SUM(LCY_OUTSTND) AS LCY_OUTSTND,
    MAX(DV_LDT) AS DV_LDT
FROM pl_classified
GROUP BY COB_DATE, BRANCH_CODE, PL_CODE
HAVING SUM(FCY_OUTSTND) <> 0 OR SUM(LCY_OUTSTND) <> 0
